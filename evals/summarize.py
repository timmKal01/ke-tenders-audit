"""Turn evals/results/*.jsonl into the markdown tables used in EVALS.md.

    python evals/summarize.py > evals/RESULTS.md
"""

import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from tasks import TASKS  # noqa: E402

RESULTS_DIR = Path(__file__).parent / "results"


def load(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def mean_sd(values: list[float]) -> str:
    if not values:
        return "n/a"
    if len(values) == 1:
        return f"{values[0]:,.0f}"
    return f"{statistics.mean(values):,.0f} (sd {statistics.stdev(values):,.0f})"


def summarize(rows: list[dict], label: str) -> str:
    model = rows[0]["model"]
    graded = [r for r in rows if r["status"] == "graded"]
    errors = [r for r in rows if r["status"] == "error"]
    lines = [f"## {label}: model `{model}`", ""]
    passed = sum(r["passed"] for r in graded)
    lines.append(f"**{passed} of {len(graded)} graded runs passed every check** "
                 f"({passed / len(graded):.0%})." if graded else "No graded runs yet.")
    if errors:
        lines.append(f"{len(errors)} more run(s) ended in an error and count as failures, "
                     f"so {passed} of {len(graded) + len(errors)} runs passed in total.")
    lines += ["", "| Task | Runs | Passed | Same result every run | Input tokens, mean | Cost per run, mean | Seconds, mean |",
              "|---|---|---|---|---|---|---|"]
    for task in TASKS:
        mine = [r for r in rows if r["task"] == task["id"]]
        if not mine:
            continue
        ok = [r for r in mine if r.get("passed")]
        outcomes = {bool(r.get("passed")) for r in mine}
        tokens = [r["usage"].get("tokens_in", 0) for r in mine if r.get("usage")]
        cost = [r["usage"].get("cost_usd", 0) for r in mine if r.get("usage")]
        secs = [r["seconds"] for r in mine if r.get("seconds")]
        lines.append(f"| {task['id']} | {len(mine)} | {len(ok)} | {'yes' if len(outcomes) == 1 else 'no'} | "
                     f"{mean_sd(tokens)} | ${statistics.mean(cost):.4f} | {mean_sd(secs)} |" if cost else
                     f"| {task['id']} | {len(mine)} | {len(ok)} | {'yes' if len(outcomes) == 1 else 'no'} | n/a | n/a | n/a |")
    lines += ["", "### Failed checks", ""]
    for r in rows:
        if r["status"] == "error":
            lines.append(f"- **{r['task']} run {r['run']}**: error `{r['error'][:160]}`")
        for c in r.get("checks", []):
            if not c["pass"]:
                lines.append(f"- **{r['task']} run {r['run']}**, check {c['check']}: {c['note']}")
    if lines[-1] == "":
        lines.append("None.")
    all_tokens = [r["usage"].get("tokens_in", 0) + r["usage"].get("tokens_out", 0) for r in graded]
    all_cost = [r["usage"].get("cost_usd", 0) for r in graded]
    if graded:
        lines += ["", f"Across graded runs: {mean_sd(all_tokens)} tokens per run, "
                      f"${statistics.mean(all_cost):.4f} per run on average."]
    return "\n".join(lines)


def main() -> None:
    files = sorted(RESULTS_DIR.glob("*.jsonl"))
    if not files:
        sys.exit("No results yet. Run evals/run_evals.py first.")
    print("# Eval results\n\nGenerated by `python evals/summarize.py`. Do not edit by hand.\n")
    for f in files:
        print(summarize(load(f), f.stem.split("-")[-1].replace("round", "Round ")))
        print()


if __name__ == "__main__":
    main()
